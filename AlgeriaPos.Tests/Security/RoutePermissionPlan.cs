namespace AlgeriaPos.Tests.Security;

/// <summary>What a route will require once it is switched to the permission model (AUTH-1 Step 2).</summary>
internal sealed record Requirement(string Kind, IReadOnlyList<string> Keys)
{
    public static readonly Requirement Open = new("open", []);
    public static readonly Requirement SignedIn = new("signed-in", []);
    public static Requirement AnyOf(params string[] keys) => new("any-of", keys);

    public bool Allows(bool signedIn, IReadOnlySet<string> effective) => Kind switch
    {
        "open" => true,
        "signed-in" => signedIn,
        _ => signedIn && Keys.Any(effective.Contains),
    };
}


    public required string Lang { get; init; }
    public bool RightToLeft => Lang == "ar";
    private readonly Dictionary<string, string> words;

    private CostReportLabels(Dictionary<string, string> words) => this.words = words;

    /// <summary>The word for a key, or the key itself (an untranslated code is shown, never hidden).</summary>
    public string this[string key] => words.TryGetValue(key, out var word) ? word : key;

    public static CostReportLabels For(string? lang) => (lang ?? "").Trim().ToLowerInvariant() switch
    {
        "ar" => new(Ar) { Lang = "ar" },
        "en" => new(En) { Lang = "en" },
        _ => new(Fr) { Lang = "fr" },
    };

